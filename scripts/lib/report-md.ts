// ROADMAP.md + ANALYSIS_REPORT.md renderers (pure: Ctx -> string).
import type { Finding } from "./types.ts";
import { categoryOf } from "./cwe.ts";
import type { Ctx } from "./report-ctx.ts";
import { cell, correctionText, counts, isStale, loc, missing, noneLine, panel, table, uncoveredDimensions, verificationIncomplete } from "./report-ctx.ts";

const NOW = new Set(["Blocker", "Critical", "High"]);

/** A recommendation table cell that never hides a verifier correction. */
function fixCell(f: Finding): string {
  return f.corrections?.length ? `${f.recommendation} ⚠ corrected by verification: ${correctionText(f).join("; ")}` : f.recommendation;
}

function item(f: Finding): string {
  const fix = `- **${f.id}** [${f.severity}/${f.confidence}, effort ${f.effort}] ${cell(f.title)} — ${loc(f)}\n  - Fix: ${cell(f.recommendation)}`;
  return correctionText(f).length ? `${fix}\n  - ⚠ corrected by verification — act on these, not the text above: ${correctionText(f).map(cell).join("; ")}` : fix;
}

export function roadmapMd(c: Ctx): string {
  const now = c.confirmed.filter((f) => NOW.has(f.severity));
  const next = c.confirmed.filter((f) => f.severity === "Medium");
  const later = c.confirmed.filter((f) => f.severity === "Low" || f.severity === "Nit");
  const k = counts(c);
  const L = ["# Roadmap", "",
    `Confirmed findings: ${k.confirmed} · Accepted risks (excluded): ${k.accepted} · Open questions: ${k.needs_human} · Refuted/deferred/unverified (never in roadmap): ${k.refuted}/${k.deferred}/${k.unverified}`, "",
    "Ranked by severity → confidence → effort (quick wins first) → id. Generated by `review.ts render`.", ""];
  if (isStale(c)) L.push("> **STALE:** the code changed after this review was scanned. Re-run before acting.", "");
  if (verificationIncomplete(c)) L.push(`> **Verification incomplete:** ${k.pending} finding(s) have no verdict and are excluded.`, "");
  const group = (title: string, fs: Finding[]) => { L.push(`## ${title}`, ""); L.push(...(fs.length ? fs.map(item) : ["_None._"]), ""); };
  group("Now — Blocker / Critical / High", now);
  group("Next — Medium", next);
  group("Later — Low / Nit", later);
  L.push("## Open questions (needs-human)", "");
  L.push(...(c.needsHuman.length ? c.needsHuman.map((f) => `- **${f.id}** ${cell(f.title)} — ${loc(f)}: ${cell(f.verifier_note ?? "verifier could not decide")}`) : ["_None._"]), "");
  return L.join("\n");
}

function findingBlock(f: Finding): string[] {
  const L = [`#### ${f.id} — ${cell(f.title)}`, "",
    `- **Severity / confidence:** ${f.severity} / ${f.confidence}${f.original_severity && f.original_severity !== f.severity ? ` (reported ${f.original_severity}, lowered by verification)` : ""} · **Effort:** ${f.effort}${f.votes?.length ? ` · **Panel:** ${panel(f)} confirmed` : ""}`,
    `- **Where:** ${loc(f)}${f.symbol ? ` (\`${cell(f.symbol)}\`)` : ""}${f.cwe ? ` · **CWE:** ${cell(f.cwe)}` : ""}`,
    ...(f.corrections?.length ? [`- **⚠ Corrected by verification** (the original text below is kept for the record; these statements replace it):`, ...correctionText(f).map((t) => `  - ${cell(t)}`)] : []),
    `- **Evidence:** ${cell(f.evidence)}`,
    `- **Impact:** ${cell(f.impact)}`,
    `- **Recommendation:** ${cell(f.recommendation)}`];
  if (f.exploit_scenario) L.push(`- **Exploit:** ${cell(f.exploit_scenario)}`);
  if (f.reporters > 1) L.push(`- **Independent reporters:** ${f.reporters}`);
  if (f.also_reported_as?.length) L.push(`- **Also reported as (consolidated):** ${f.also_reported_as.map(cell).join(", ")}${f.consolidation_note ? ` — ${cell(f.consolidation_note)}` : ""}`);
  L.push("");
  return L;
}

function prose(title: string, text: string | null, stage: string): string[] {
  return [`## ${title}`, "", text?.trim() ? text.trim() : missing(stage), ""];
}

export function analysisMd(c: Ctx): string {
  const k = counts(c);
  const ev = c.evidence;
  const name = c.scope?.name ?? "review";
  const L = [`# Comprehensive Code Analysis — ${name}`, "",
    "Rendered deterministically by `review.ts render` from `evidence.json`, `topology.json`, `architecture.json`, `coverage.json` and verified `findings.json`. Every count is script-owned.", ""];

  // Banners
  if (isStale(c)) L.push("> **STALE REVIEW:** the code under review changed after the scan (tree fingerprint mismatch in `REVISION.json`). Findings may point at moved or fixed code.", "");
  if (verificationIncomplete(c)) L.push(`> **VERIFICATION INCOMPLETE:** ${k.pending} finding(s) have no verdict and are excluded from every count below.`, "");

  // Executive summary
  const sev = new Map<string, number>();
  for (const f of c.confirmed) sev.set(f.severity, (sev.get(f.severity) ?? 0) + 1);
  L.push("## Executive summary", "");
  if (ev) L.push(`- Files: ${ev.total_files ?? "?"} (${ev.source_files ?? "?"} source, ${ev.test_files ?? "?"} test) · Code lines: ${ev.total_code_lines ?? "?"}`,
    `- Languages: ${Object.entries(ev.languages ?? {}).map(([l, v]: [string, any]) => `${l} ${typeof v === "object" ? v?.lines ?? "?" : v}`).join(", ") || "—"}`);
  else L.push(`- Evidence: ${missing("assess")}`);
  L.push(`- Findings: **${k.confirmed} confirmed** (${["Blocker", "Critical", "High", "Medium", "Low", "Nit"].filter((s) => sev.get(s)).map((s) => `${s} ${sev.get(s)}`).join(", ") || "none"}) · ${k.needs_human} need a human · ${k.accepted} accepted risk · ${k.refuted} refuted · ${k.deferred} deferred (coverage gap) · ${k.unverified} unverified (below the verification floor) · ${k.pending} pending`);
  if (c.architecture?.one_thing) L.push(`- If only one thing changes: ${cell(c.architecture.one_thing)}`);
  if (c.revision) L.push(`- Revision: \`${cell(c.revision.commit)}\`${c.revision.dirty ? " (dirty tree)" : ""} · scanned ${cell(c.revision.scanned_at)}`);
  L.push("");

  // Scope & methodology
  L.push("## Scope & methodology", "");
  if (c.scope) L.push(`- Source: \`${cell(c.scope.source)}\`${c.scope.module ? ` · module \`${cell(c.scope.module)}\`` : ""}`, `- Dimensions: ${(c.scope.dimensions ?? []).join(", ")} · security effort: ${c.scope.security_effort}`);
  L.push("- Stages: preflight → assess (deterministic evidence + scanners) → map → deep (module × dimension) → security (threat model, component × category sweep) → verify → architecture → report.",
    "- Verification: security candidates face a three-lens panel (REACHABILITY / IMPACT / DEFENSES); **2 of 3** must confirm, severity is the **median of confirming votes and never raised**, `high` confidence requires 3/3. Other findings get one independent verifier. Refuted findings appear only in the appendix.",
    "- Repository text is treated as data, never instructions; secrets are redacted in every output.", "");
  if (c.scanners?.length) {
    L.push(...table(["Scanner", "Status", "Version", "Findings", "Network", "Note"],
      c.scanners.map((s) => [s.id ?? s.tool, s.status, s.version, s.findings, s.network ? "yes" : "no", s.error])), "");
  } else L.push(`Scanners: ${missing("assess")}`, "");

  // Coverage
  L.push("## Coverage", "");
  const cov = c.coverage;
  if (cov) {
    L.push(`- Files read by agents: ${cov.files_read ?? "?"} of ${cov.files_total ?? "?"} (${cov.files_read_pct ?? "?"}%)`, "");
    L.push(...table(["Top-level dir", "Status", "Files", "Files read", "Reason"],
      (cov.top_level ?? []).map((d: any) => [d.dir, d.status, d.files, d.files_read, d.reason])), "");
    const gaps: string[] = [];
    for (const s of cov.lost_shards ?? []) gaps.push(`- Lost shard: \`${cell(s)}\``);
    for (const s of cov.deferred_shards ?? []) gaps.push(`- Deferred shard (agent cap): \`${cell(s)}\``);
    for (const s of cov.capped_shards ?? []) gaps.push(`- Findings cap: \`${cell(s.shard)}\` filed ${s.filed}, the ${s.kept} most severe were kept`);
    for (const s of cov.scanners?.failed ?? []) gaps.push(`- Scanner **${cell(s.id)}** ${cell(s.status)}: ${cell(s.error)}`);
    for (const s of cov.scanners?.missing ?? []) gaps.push(`- Scanner **${cell(s)}** not installed`);
    for (const s of cov.not_reached ?? []) gaps.push(`- Not reached: \`${cell(s)}\``);
    for (const d of (cov.top_level ?? []).filter((x: any) => x.status === "unaccounted")) gaps.push(`- Unaccounted directory: \`${cell(d.dir)}\``);
    L.push("### Gaps", "", ...(gaps.length ? gaps : ["_No coverage gaps recorded._"]), "");
    const unc = [...uncoveredDimensions(c)];
    if (unc.length) L.push(`Dimensions **not fully covered**: ${unc.join(", ")}. Their "no findings" lines below mean "not fully examined", not "clean".`, "");
  } else L.push(missing("verify"), "");

  // Architecture summary
  L.push("## Architecture", "");
  const a = c.architecture;
  if (a) {
    L.push(`**Style:** ${cell(a.style)}`, "", String(a.summary ?? "").trim(), "", "Full detail: [ARCHITECTURE.md](ARCHITECTURE.md).", "");
    if (Array.isArray(a.quality_attributes) && a.quality_attributes.length)
      L.push(...table(["Quality attribute (ISO 25010)", "Rating", "Rationale"], a.quality_attributes.map((q: any) => [q.name, q.rating === "unavailable" ? "unavailable" : `${q.rating}/5`, q.rationale])), "");
  } else L.push(missing("architecture"), "");
  const arch = c.confirmed.filter((f) => f.dimension === "architecture");
  L.push(...(arch.length ? arch.flatMap(findingBlock) : [noneLine(c, "architecture"), ""]));

  // Security
  L.push("## Security review", "");
  L.push("### Threat model", "", c.threatModel?.trim() || missing("security"), "");
  const sec = c.confirmed.filter((f) => f.dimension === "security");
  if (sec.length) {
    L.push(...table(["ID", "CWE", "Category", "Severity", "Panel", "Location", "Exploit", "Fix"],
      sec.map((f) => [f.id, f.cwe, f.cwe ? categoryOf(f.cwe).name : f.category, f.severity, panel(f), `${f.file}:${f.line}`, f.exploit_scenario, fixCell(f)])), "");
    L.push(...sec.flatMap(findingBlock));
  } else L.push(noneLine(c, "security", "confirmed security findings"), "");

  // Code quality
  L.push("## Code quality", "");
  if (ev) {
    const god = ev.god_class_candidates ?? [];
    const lm = ev.long_method_candidates ?? [];
    const th = ev.thresholds ?? {};
    L.push(`- God-file candidates (≥${th.god_file_lines ?? 500} lines): ${god.length} · Long-method candidates (≥${th.long_method_lines ?? 50} lines): ${lm.length}. Candidates are heuristics, not verdicts.`, "");
    if (god.length) L.push("### God-file candidates", "", ...table(["File", "Lines"], god.slice(0, 25).map((g: any) => [g.file, g.lines ?? g.sloc])), "");
    if (lm.length) L.push("### Long-method candidates", "", ...table(["Function", "Location", "Lines", "Complexity"], lm.slice(0, 25).map((m: any) => [m.name, `${m.file}:${m.line}`, m.lines, m.complexity])), "");
    if ((ev.complexity_top ?? []).length) L.push("### Most complex files", "", ...table(["File", "Complexity", "Functions"], ev.complexity_top.slice(0, 15).map((x: any) => [x.file, x.complexity, x.functions])), "");
    if ((ev.hotspots ?? []).length) L.push("### Hotspots (churn × complexity)", "", `Formula: ${cell(ev.hotspot_formula ?? "churn × complexity")}`, "", ...table(["File", "Churn", "Complexity", "Score"], ev.hotspots.slice(0, 15).map((h: any) => [h.file, h.churn, h.complexity, h.score])), "");
    else if (ev.churn && ev.churn.available === false) L.push("_Hotspots unavailable: no git history._", "");
    if ((ev.ownership ?? []).length) L.push("### Ownership", "", ...table(["Directory", "Authors", "Top author share", "Bus factor"], ev.ownership.map((o: any) => [o.dir, o.authors, o.top_author_share, o.bus_factor])), "");
  } else L.push(missing("assess"), "");
  const qual = c.confirmed.filter((f) => f.dimension === "quality");
  L.push(...(qual.length ? qual.flatMap(findingBlock) : [noneLine(c, "quality"), ""]));

  // Tests
  L.push("## Test posture", "");
  if (ev?.measured_coverage) L.push(`- Measured coverage: ${cell(typeof ev.measured_coverage === "object" ? JSON.stringify(ev.measured_coverage) : ev.measured_coverage)}`, "");
  else if (ev) {
    const src = Number(ev.source_files ?? 0), tst = Number(ev.test_files ?? 0);
    L.push(`- Test files: ${tst} vs ${src} source files (ratio ${src ? Math.round((100 * tst) / src) : 0}%).`,
      "- **PROXY, not measured coverage:** this counts test files only. Measured line/branch coverage requires running the project's coverage tool (approved in preflight).", "");
  } else L.push(missing("assess"), "");
  const tests = c.confirmed.filter((f) => f.dimension === "testing");
  L.push(...(tests.length ? tests.flatMap(findingBlock) : [noneLine(c, "testing"), ""]));

  // Dependencies
  L.push("## Dependencies", "");
  if (ev?.manifests?.length) L.push(`- Manifests: ${ev.manifests.map((m: string) => `\`${cell(m)}\``).join(", ")}`, "");
  const deps = c.confirmed.filter((f) => f.dimension === "dependencies");
  L.push(...(deps.length ? table(["ID", "Severity", "Source", "Location", "Title", "Fix"], deps.map((f) => [f.id, f.severity, f.source ?? "agent", `${f.file}:${f.line}`, f.title, fixCell(f)])) : [noneLine(c, "dependencies")]), "");

  // Other dimensions
  L.push("## Findings by dimension", "");
  for (const d of ["performance", "operability", "data"]) {
    const fs = c.confirmed.filter((f) => f.dimension === d);
    L.push(`### ${d}`, "", ...(fs.length ? fs.flatMap(findingBlock) : [noneLine(c, d), ""]));
  }

  L.push("## Accepted risks", "");
  L.push(...(c.accepted.length ? table(["ID", "Severity", "Location", "Title", "Reason", "By", "At"], c.accepted.map((f) => [f.id, f.severity, `${f.file}:${f.line}`, f.title, f.accepted?.reason, f.accepted?.by, f.accepted?.at])) : ["_None._"]), "");

  L.push("## Changes since baseline", "");
  if (c.diff) {
    L.push(`Baseline: \`${cell(c.diff.baseline)}\` · new ${(c.diff.new ?? []).length} · fixed ${(c.diff.fixed ?? []).length} · persisting ${(c.diff.persisting ?? []).length}`, "");
    if ((c.diff.fixed ?? []).length) L.push(...table(["Fixed", "Title", "Location"], c.diff.fixed.map((f: any) => [f.id, f.title, `${f.file}:${f.line}`])), "");
    if ((c.diff.new ?? []).length) L.push(`New: ${c.diff.new.map((i: string) => `\`${cell(i)}\``).join(", ")}`, "");
  } else L.push("_No baseline given._", "");

  L.push(...prose("Assessment", c.assessment, "assess"));
  L.push(...prose("Analyst notes", c.notes, "report"));

  L.push("## Appendix", "", "### Needs a human", "");
  L.push(...(c.needsHuman.length ? c.needsHuman.map((f) => `- **${f.id}** ${cell(f.title)} — ${loc(f)}. Question: ${cell(f.verifier_note ?? "—")}`) : ["_None._"]), "");
  L.push("### Refuted (kept for audit)", "");
  L.push(...(c.refuted.length ? c.refuted.map((f) => `- **${f.id}** ${cell(f.title)} — ${loc(f)}. Verifier: ${cell(f.verifier_note ?? (f.votes ?? []).map((v) => `${v.lens}: ${v.note}`).join("; "))}`) : ["_None._"]), "");
  L.push("### Deferred (coverage gap — not verified)", "");
  L.push(...(c.deferred.length ? c.deferred.map((f) => `- **${f.id}** [${f.severity}] ${cell(f.title)} — ${loc(f)}`) : ["_None._"]), "");
  L.push(`### Unverified (below the verification floor${c.scope?.verify_min_severity ? `, ${c.scope.verify_min_severity}` : ""} — reported as filed)`, "");
  L.push(...(c.unverified.length ? c.unverified.map((f) => `- **${f.id}** [${f.severity}] ${cell(f.title)} — ${loc(f)}`) : ["_None._"]), "");
  return L.join("\n");
}
