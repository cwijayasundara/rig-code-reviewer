// Regenerate data/cwe-categories.json from the MITRE CWE XML catalog.
//   curl -sSfLO https://cwe.mitre.org/data/xml/cwec_latest.xml.zip && unzip cwec_latest.xml.zip
//   node --disable-warning=ExperimentalWarning scripts/tools/build-cwe.ts cwec_vX.Y.xml
// Mapping: every weakness maps to its nearest entry of view CWE-1003
// ("Weaknesses for Simplified Mapping of Published Vulnerabilities"): itself if
// it is in the view, else the closest ancestor in the view following ChildOf
// edges (view 1003 first, then the research view 1000, then any view).
import { readFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { writeJson } from "../lib/util.ts";

interface W { id: number; name: string; alt?: string; deprecated: boolean; parents: { id: number; view: number; primary: boolean }[] }

const unescape = (s: string) => s.replace(/&apos;/g, "'").replace(/&quot;/g, '"').replace(/&lt;/g, "<").replace(/&gt;/g, ">").replace(/&amp;/g, "&").replace(/\s+/g, " ").trim();

/** Common name: the first alternate term (CWE 5.x), a legacy "('SQL Injection')" suffix (CWE 4.x), else the full name. */
const COMMON: Record<number, string> = { 78: "OS Command Injection", 352: "Cross-Site Request Forgery (CSRF)", 918: "Server-Side Request Forgery (SSRF)", 611: "XML External Entity (XXE)", 1336: "Server-Side Template Injection", 1333: "Regular Expression Denial of Service (ReDoS)" };

export function shortName(name: string, alt?: string, id?: number): string {
  if (id !== undefined && COMMON[id]) return COMMON[id]!;
  if (alt && alt.length <= 40) return alt;
  const m = name.match(/\('([^']+)'\)\s*$/);
  return m ? m[1]! : name;
}

export function parseCatalog(xml: string): { version: string; weaknesses: Map<number, W>; viewMembers: Set<number> } {
  const version = xml.match(/<Weakness_Catalog[^>]*\sVersion="([^"]+)"/)?.[1] ?? "unknown";
  const weaknesses = new Map<number, W>();
  for (const m of xml.matchAll(/<Weakness ID="(\d+)" Name="([^"]*)"[^>]*Status="([^"]*)"[^>]*>([\s\S]*?)<\/Weakness>/g)) {
    const parents = [...m[4]!.matchAll(/<Related_Weakness Nature="ChildOf" CWE_ID="(\d+)" View_ID="(\d+)"(?:[^>]*Ordinal="(\w+)")?[^>]*\/>/g)]
      .map((r) => ({ id: Number(r[1]), view: Number(r[2]), primary: r[3] === "Primary" }));
    const alt = m[4]!.match(/<Alternate_Term>\s*<Term>([^<]*)<\/Term>/)?.[1];
    weaknesses.set(Number(m[1]), { id: Number(m[1]), name: unescape(m[2]!), alt: alt ? unescape(alt) : undefined, deprecated: m[3] === "Deprecated", parents });
  }
  const view = xml.match(/<View ID="1003"[\s\S]*?<\/View>/)?.[0] ?? "";
  const viewMembers = new Set([...view.matchAll(/<Has_Member CWE_ID="(\d+)" View_ID="1003"/g)].map((r) => Number(r[1])));
  for (const w of weaknesses.values()) for (const p of w.parents) if (p.view === 1003) { viewMembers.add(w.id); viewMembers.add(p.id); }
  return { version, weaknesses, viewMembers };
}

export function buildMapping(c: ReturnType<typeof parseCatalog>) {
  const inView = c.viewMembers;
  const rank = (p: { view: number; primary: boolean }) => (p.view === 1003 ? 0 : p.view === 1000 ? 1 : 2) * 2 + (p.primary ? 0 : 1);
  const nearest = (id: number): number | null => {
    const seen = new Set<number>([id]);
    let frontier = [id];
    while (frontier.length) {
      const next: number[] = [];
      for (const f of frontier) {
        if (inView.has(f)) return f;
        const w = c.weaknesses.get(f);
        for (const p of [...(w?.parents ?? [])].sort((a, b) => rank(a) - rank(b) || a.id - b.id)) if (!seen.has(p.id)) { seen.add(p.id); next.push(p.id); }
      }
      frontier = next;
    }
    return null;
  };
  const categories: Record<string, { name: string; title: string }> = {};
  for (const id of [...inView].sort((a, b) => a - b)) {
    const w = c.weaknesses.get(id);
    if (w) categories[String(id)] = { name: shortName(w.name, w.alt, id), title: w.name };
  }
  const category_of: Record<string, number | null> = {};
  for (const w of [...c.weaknesses.values()].sort((a, b) => a.id - b.id)) if (!w.deprecated) category_of[String(w.id)] = nearest(w.id);
  return { categories, category_of };
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const file = process.argv[2];
  if (!file) { console.error("usage: build-cwe.ts <cwec_vX.Y.xml>"); process.exit(2); }
  const cat = parseCatalog(readFileSync(file, "utf8"));
  const { categories, category_of } = buildMapping(cat);
  const out = join(dirname(fileURLToPath(import.meta.url)), "..", "..", "data", "cwe-categories.json");
  writeJson(out, {
    source: `Generated by scripts/tools/build-cwe.ts from the MITRE CWE catalog ${cat.version} (https://cwe.mitre.org/). CWE™ is free to use per the CWE Terms of Use; Copyright © 2006–2026, The MITRE Corporation. CWE is a trademark of The MITRE Corporation.`,
    cwe_version: cat.version, view: "CWE-1003", categories, category_of,
  });
  console.log(`cwe ${cat.version}: ${Object.keys(categories).length} view entries, ${Object.keys(category_of).length} weaknesses mapped -> ${out}`);
}
